'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const root=path.join(__dirname,'../dist');
const filename='assets/westhofen/westhofen-memorial-style2-v2.svg';
const url=filename+'?v=westhofen-style2v2';
const source=fs.readFileSync(path.join(root,filename),'utf8');
assert.match(source,/<svg\b/);
assert.match(source,/viewBox="0 0 768 512"/);
for(const layer of ['stone-frame-v2','altar-steps-v2','bronze-emblem-v2'])assert.ok(source.includes('id="'+layer+'"'),layer);
assert.doesNotMatch(source,/<(?:script|image|foreignObject|text)\b/i);
assert.doesNotMatch(source,/\bon\w+\s*=|url\(https?:|data:/i);
assert.ok(Buffer.byteLength(source)<100000,'mobile SVG download budget');
const manager=fs.readFileSync(path.join(root,'asset-manager.js'),'utf8');
const art=fs.readFileSync(path.join(root,'westhofen-art.js'),'utf8');
assert.ok(manager.includes(url),'shared preload uses the V2 asset');
assert.ok(art.includes(url),'draw path uses the same V2 asset');
assert.ok(!art.includes('westhofen-memorial-style2-v1.webp'),'V1 is retained on disk but not requested by runtime');
assert.ok(fs.existsSync(path.join(root,'assets/westhofen/westhofen-memorial-style2-v1.webp')),'V1 fallback file remains available');
assert.match(art,/ctx\.drawImage\(memorialSprite,m\.x-225,m\.y-265,450,300\)/,'preserve world anchor');
console.log('Westhofen V2 SVG: safe static source, preloaded once, matching URL, preserved V1 and anchor');

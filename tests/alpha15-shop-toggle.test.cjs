'use strict';
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
(async()=>{
  const root=path.resolve(__dirname,'../dist/alpha1-5');
  const {bindPortraitShop}=await import(path.join(root,'shop-toggle.mjs'));
  const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
  const css=fs.readFileSync(path.join(root,'styles.css'),'utf8');
  assert.match(html,/id="shopToggle"[^>]*aria-controls="upgradeShop"[^>]*aria-expanded="false"/);
  assert.match(html,/id="upgradeShop"[^>]*aria-label="Denkmal verbessern"/);
  assert.match(html,/id="techTab"[^>]*aria-pressed="true"/);
  assert.match(html,/id="upgradeTab"[^>]*aria-pressed="false"/);
  let open=false,focused=false,click,keydown,change;
  const attrs={};
  const layout={classList:{toggle(name,value){assert.equal(name,'portrait-shop-open');open=value;}}};
  const toggle={hidden:false,textContent:'',addEventListener(name,fn){if(name==='click')click=fn;},setAttribute(name,value){attrs[name]=value;},focus(){focused=true;}};
  const media={matches:true,addEventListener(name,fn){if(name==='change')change=fn;}};
  const doc={addEventListener(name,fn){if(name==='keydown')keydown=fn;}};
  assert.equal(bindPortraitShop({layout,toggle,media,document:doc}),true);
  assert.equal(open,false);assert.equal(toggle.hidden,false);assert.equal(attrs['aria-expanded'],'false');
  click();assert.equal(open,true);assert.equal(attrs['aria-expanded'],'true');assert.equal(toggle.textContent,'✕ Schließen');
  keydown({key:'Escape'});assert.equal(open,false);assert.equal(attrs['aria-expanded'],'false');assert.equal(focused,true);
  click();media.matches=false;change();assert.equal(open,false);assert.equal(toggle.hidden,true);assert.equal(attrs['aria-expanded'],'false');
  media.matches=true;change();assert.equal(toggle.hidden,false);assert.equal(attrs['aria-expanded'],'false');
  assert.match(css,/@media\(max-width:650px\) and \(orientation:portrait\)/);
  assert.match(css,/\.layout:not\(\.portrait-shop-open\) \.shop/);
  assert.match(css,/\.layout\.portrait-shop-open \.shop/);
  assert.match(css,/\.shop-toggle\{display:block/);
  console.log('Alpha 1.5 portrait shop open/close, Escape, and rotation checks passed.');
})().catch(error=>{console.error(error);process.exitCode=1;});

'use strict';
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
(async()=>{
  const root=path.resolve(__dirname,'../dist/alpha1-5');
  const {bindShopToggle}=await import(path.join(root,'shop-toggle.mjs'));
  const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
  const css=fs.readFileSync(path.join(root,'styles.css'),'utf8');
  assert.match(html,/id="shopToggle"[^>]*aria-controls="upgradeShop"[^>]*aria-expanded="true"/);
  assert.match(html,/id="upgradeShop"[^>]*aria-label="Denkmal verbessern"/);
  assert.match(html,/id="techTab"[^>]*aria-pressed="true"/);
  assert.match(html,/id="upgradeTab"[^>]*aria-pressed="false"/);
  let collapsed=false,click;
  const attrs={"aria-expanded":"true"};
  const app={classList:{toggle(name){assert.equal(name,'shop-collapsed');collapsed=!collapsed;return collapsed;}}};
  const button={textContent:'⚡ UPGRADES',addEventListener(name,fn){assert.equal(name,'click');click=fn;},setAttribute(name,value){attrs[name]=value;}};
  assert.equal(bindShopToggle(app,button),true);
  click();
  assert.equal(collapsed,true);
  assert.equal(attrs['aria-expanded'],'false');
  assert.equal(button.textContent,'⚡ UPGRADES');
  click();
  assert.equal(collapsed,false);
  assert.equal(attrs['aria-expanded'],'true');
  assert.equal(button.textContent,'× UPGRADES SCHLIESSEN');
  assert.match(css,/@media\(max-width:650px\) and \(orientation:portrait\)/);
  assert.match(css,/#app\.shop-collapsed \.shop\{display:none\}/);
  assert.match(css,/\.shop-toggle\{display:block/);
  console.log('Alpha 1.5 portrait upgrade-menu toggle checks passed.');
})().catch(error=>{console.error(error);process.exitCode=1;});

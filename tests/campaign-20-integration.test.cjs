'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const original=fs.readFileSync(path.join(__dirname,'game.test.cjs'),'utf8');
const cut=original.indexOf("if(process.env.TEST_MOBILE==='1'){");
assert.ok(cut>0,'existing game VM bootstrap must remain available');
let setup=original.slice(0,cut);
const hook="vm.runInContext(fs.readFileSync(path.join(root,'levels.js'),'utf8'),sandbox);";
assert.ok(setup.includes(hook),'planner must load before levels');
setup=setup.replace(hook,"vm.runInContext(fs.readFileSync(path.join(root,'campaign-20-wave-plan.js'),'utf8'),sandbox);"+hook);
const checks=String.raw`
const T=sandbox.test, P=sandbox.DenkmalCampaign20;
assert.ok(P);
const bosses=[];
for(let level=1;level<=7;level++){
  T.startGame(1);
  T.resetGame(level,'campaign');
  const g=T.game, chapter=P.chapter(level);
  assert.equal(g.wave,chapter.firstWave,'campaign begins at the right chapter start');
  assert.equal(g.waveTotal,P.describe(level,g.wave).count,'live spawn count uses planner');
  assert.equal(T.waveSize(chapter.lastWave),P.describe(level,chapter.lastWave).count);
  assert.equal(T.enemyTypeForSpawn(chapter.firstWave+9,0),level===3?'uprooted':'boss');
  assert.equal(T.enemyTypeForSpawn(chapter.lastWave,0),level===3?'uprooted':'boss');
  const lanes=sandbox.DenkmalLevels.getWaveGates(level,chapter.firstWave,'campaign');
  assert.ok(lanes.length>=1&&lanes.length<=g.level+4,'chapter has legal entry lanes');
  assert.equal(T.wavePlan(chapter.lastWave).name.includes('BOSS'),true);
  g.wave=chapter.lastWave-1;
  T.endWave();
  assert.equal(T.state,'perk','chapter continues through wave 19');
  T.startGame(1);
  T.resetGame(level,'campaign');
  const final=T.game;
  final.wave=chapter.lastWave;final.waveTotal=T.waveSize(final.wave);
  T.spawnEnemy();
  assert.equal(final.enemies[0].type,level===3?'uprooted':'boss','live spawn injects the correct chapter boss');
  bosses.push(final.enemies[0].type);
  T.endWave();
  assert.equal(T.state,'levelcomplete','only wave 20 completes chapter');
}
assert.equal(bosses.length,7);
T.startGame(1);
T.resetGame(2,'endless');
assert.equal(T.game.wave,6,'endless start wave remains legacy');
assert.equal(T.waveSize(6),23,'endless spawn count remains legacy');
T.resetGame(1,'campaign-pilot');
assert.equal(T.game.wave,1,'pilot remains legacy');
assert.equal(T.waveSize(1),9,'pilot wave count remains legacy');
console.log('TD2 integrated campaign: 7 chapters, real boss spawns, wave-20 unlock, endless and pilot isolation passed');
`;
vm.runInNewContext(setup+checks,{require,process,console,__dirname,setTimeout,clearTimeout},{filename:'campaign-20-integration.test.cjs',timeout:20000});

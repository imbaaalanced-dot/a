const assert=require('node:assert/strict');
const P=require('../dist/portal-run.js');
let r=P.create({runId:'test',seed:1,heroId:'marcel',startBudget:75,maxSections:3});
assert.equal(r.gold,75);assert.equal(r.phase,'build');
assert.equal(P.refund([{spent:25},{spent:60}]),85);
assert.throws(()=>P.refund([{spent:NaN}]));assert.throws(()=>P.refund([{spent:-1}]));
r=P.reduce(r,{type:'START'}).run;assert.equal(r.phase,'combat');
r=P.reduce(r,{type:'CLEAR'}).run;assert.equal(r.phase,'build');
r=P.reduce(r,{type:'START'}).run;r=P.reduce(r,{type:'CLEAR'}).run;assert.equal(r.phase,'perk');
r=P.reduce(r,{type:'CHOOSE',id:'power'}).run;assert.equal(r.phase,'exit');
r=P.reduce(r,{type:'ENTER',gold:10,towers:[{spent:25},{spent:60}],hp:45,maxHp:100}).run;
assert.equal(r.gold,113.75);assert.equal(r.heroHp,55);assert.equal(r.phase,'loading');
assert.deepEqual(P.reduce(r,{type:'ENTER',gold:1000,towers:[],hp:100,maxHp:100}).run,r);
r=P.reduce(r,{type:'READY'}).run;assert.equal(r.section,2);assert.equal(r.phase,'build');
const data=new Map(),storage={getItem:k=>data.get(k)||null,setItem:(k,v)=>data.set(k,v)};
const s=P.createStore(storage);assert.equal(s.load().status,'missing');assert.equal(s.save(r,null),true);
assert.equal(s.load().run.section,2);assert.equal(s.save(r,-1),false);
console.log('portal run: state, economics, checkpoint and duplicate transition checks passed');
// Invalid checkpoints must be rejected before gameplay consumes them.
data.set(P.KEY,JSON.stringify({...r,offers:['unknown']}));assert.equal(s.load().status,'corrupt');
data.set(P.KEY,JSON.stringify({...r,perkRanks:{unknown:1}}));assert.equal(s.load().status,'corrupt');
data.set(P.KEY,JSON.stringify({...r,checkpoint:{hero:{hp:-1},gold:0,towers:[],wave:1}}));assert.equal(s.load().status,'corrupt');
// Previously saved bare v1 runs must migrate without losing the revision checkpoint.
data.set(P.KEY,JSON.stringify(r));
assert.equal(s.load().run.revision,r.revision);
assert.equal(s.save(r,r.revision),true);
const migrated=JSON.parse(data.get(P.KEY));
assert.equal(migrated.schemaVersion,2);
assert.equal(migrated.run.runId,r.runId);
assert(Number.isFinite(migrated.lastUpdated));
const stale=P.createStore(storage);assert.equal(stale.load().run.revision,r.revision);
const advanced=P.reduce(r,{type:'START'}).run;
assert.equal(s.save(advanced,r.revision),true);
assert.equal(stale.save(r,r.revision),false,'old tab cannot overwrite new revision');
const previous=data.get(P.KEY);
data.set(P.KEY,'{');assert.equal(P.createStore(storage).load().status,'corrupt');
assert.equal(P.createStore(storage).save(r,null),false,'bad JSON may not be replaced');
assert.equal(data.get(P.KEY),'{');
data.set(P.KEY,JSON.stringify({schemaVersion:22,lastUpdated:12,run:r}));
assert.equal(P.createStore(storage).load().status,'incompatible');
assert.equal(P.createStore(storage).save(r,null),false);
data.set(P.KEY,JSON.stringify({schemaVersion:2,lastUpdated:12}));
assert.equal(P.createStore(storage).load().status,'corrupt','partial envelope is rejected');
data.set(P.KEY,previous);
const refused=P.createStore({getItem:k=>data.get(k),setItem(){throw Error('quota')}});
assert.equal(refused.load().status,'ok');
assert.equal(refused.save(advanced,advanced.revision),false,'failed write is reported');
const firstTab=P.createStore(storage),secondTab=P.createStore(storage);
const sameRevision=firstTab.load().run;
secondTab.load();
assert.equal(firstTab.save({...sameRevision,gold:sameRevision.gold+1},sameRevision.revision),true);
assert.equal(secondTab.save(sameRevision,sameRevision.revision),false,'same-revision stale tab may not overwrite a concurrent save');

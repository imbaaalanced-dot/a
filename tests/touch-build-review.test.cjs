'use strict';
// Port of PR #84 onto the current campaign and menu, with a menu-dismissal guard.
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.resolve(__dirname,'../dist');
const read=name=>fs.readFileSync(path.join(root,name),'utf8');
const game=read('game.js'),levels=read('levels.js'),css=read('portrait-patch.css'),html=read('index.html');
const lootUI=read('loot-ui.js'),lootCss=read('loot.css');

assert.match(game,/function buildTowerAt\(p\)\{/);
assert.match(game,/function buildTower\(\)\{buildTowerAt\(towerPosition\(\)\);\}/);
assert.match(game,/if\(state!=='playing'\)return;\s+if\(inPortal\(\)/);
assert.match(game,/let buildTapStart=null;/);
assert.match(game,/e\.pointerType==='mouse'\|\|state!=='playing'\|\|document\.querySelector/);
assert.match(game,/\$\('hudMenu'\)\?\.open\)return;\s+buildTapStart=/);
assert.match(game,/canvas\.addEventListener\('pointercancel',\(\)=>\{buildTapStart=null;\}\)/);
assert.match(game,/e\.pointerId!==start\.id/);
assert.match(game,/Math\.hypot\(e\.clientX-start\.x,e\.clientY-start\.y\)>14/);
assert.match(game,/nearestSlot\(screenToWorld\(e\.clientX,e\.clientY\),game\.level,120\)/);
assert.match(game,/if\(slot\)buildTowerAt\(slot\)/);
assert.match(game,/setHidden\(\$\('arsenal'\),!playing\)/);
assert.match(game,/setDisabled\(\$\('buildBtn'\),!playing\|\|!buildContext/);
assert.match(game,/portalRun\.phase==='exit'\|\|game\.essence/);
assert.match(css,/\.arsenal button:disabled\{opacity:\.5/);
assert.match(css,/\.controls \.action-btn:disabled\{opacity:\.55/);
assert.match(lootUI,/b\.dataset\.rarity=item\.rarity/);
assert.match(lootCss,/data-rarity="epic"/);
assert.match(lootCss,/data-rarity="legendary"/);
assert.match(lootCss,/appearance:none;-webkit-appearance:none/);

const box={localStorage:{getItem:()=>null,setItem(){}}};
vm.createContext(box);
vm.runInContext(read('persisted-state.js'),box);
vm.runInContext(levels,box);
const slots=box.DenkmalLevels.levels[2].slots;
assert.ok(slots.length>0);
const sample=slots[0];
assert.equal(box.DenkmalLevels.nearestSlot(sample,2),sample);
const probe={x:sample.x+100,y:sample.y+100};
assert.equal(box.DenkmalLevels.nearestSlot(probe,2,0),null);
assert.match(levels,/function nearestSlot\(p,level=2,radius=88\)/);
assert.match(html,/game\.js\?v=v410a1touch2/);
assert.match(html,/levels\.js\?v=level7-touch2/);
assert.match(html,/portrait-patch\.css\?v=v410a1touch2/);
assert.match(html,/loot-ui\.js\?v=contrastglow2/);
assert.match(html,/loot\.css\?v=contrastglow2/);
console.log('Touch build: safe tap guards, optional snap radius and stable build controls passed');

'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const source=fs.readFileSync('dist/style2-ambience.js','utf8');
const html=fs.readFileSync('dist/index.html','utf8'),game=fs.readFileSync('dist/game.js','utf8');
assert.ok(html.indexOf('style2-ambience.js')>-1&&html.indexOf('style2-ambience.js')<html.indexOf('game.js?v='));
assert.match(html,/style2-ui-polish\.css/);
assert.match(game,/Style2Ambience\?\.drawGround/);
assert.match(game,/Style2Ambience\?\.drawAir/);
let creations=0,images=0,rects=0,saved=0;
const paint=new Proxy({globalAlpha:1,createRadialGradient(){return {addColorStop(){}};},drawImage(){images++;},fillRect(){rects++;},save(){saved++;},restore(){saved--;}},{get:(o,k)=>k in o?o[k]:()=>{}});
const box={Math,document:{createElement(){creations++;return {width:0,height:0,getContext(){return paint;}};}}};
vm.createContext(box);vm.runInContext(source,box);
const a=box.Style2Ambience,layout={center:{x:1536,y:1536},gates:[{x:1536,y:900},{x:2000,y:1400}],airGate:{x:1800,y:550}};
const before=JSON.stringify(layout);
a.drawGround(paint,6,layout,2,{low:false});
const warm=creations;assert.equal(warm,2,'amber and blue gradients are the only canvases created');
for(let frame=0;frame<120;frame++)a.drawGround(paint,6,layout,frame/60,{low:false});
assert.equal(creations,warm,'no canvas allocations per frame');assert.ok(images>200);
const camera={x:1300,y:1240},camBefore=JSON.stringify(camera);
const p1=a.motes(3,camera,700,550,1,{low:false}),p2=a.motes(3,camera,700,550,1,{low:false});
assert.equal(JSON.stringify(p1),JSON.stringify(p2),'fixed coordinates and clock produce deterministic air particles');
assert.ok(p1.length>0&&p1.length<=a.MAX_MOTES);
assert.equal(a.motes(3,camera,700,550,1,{low:true}).length,0,'low graphics disables moving ambience');
assert.ok(p1.every(p=>p.x>=camera.x-15&&p.x<=camera.x+715&&p.y>=camera.y-15&&p.y<=camera.y+565));
assert.equal(JSON.stringify(layout),before,'ambience must not mutate authored gates');
assert.equal(JSON.stringify(camera),camBefore,'render must not move the camera');
assert.equal(a.drawAir(paint,3,camera,700,550,1,{low:false}),p1.length);
assert.equal(a.drawAir(paint,3,camera,700,550,1,{low:true}),0);
assert.equal(creations,warm,'moving motes never allocate canvases');
assert.equal(saved,0,'render state must be restored');
assert.ok(rects>0);
const css=fs.readFileSync('dist/style2-ui-polish.css','utf8');
assert.match(css,/\.arsenal button\.selected/);
assert.doesNotMatch(css,/min-height|pointer-events|\bposition\s*:/,'appearance patch must not alter touch layout');
console.log('Style 2 phase 7 ambience: deterministic particles, cached light, mobile-low fallback, unchanged layout and HUD checks passed.');
